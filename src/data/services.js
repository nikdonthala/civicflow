export const flatServices = serviceCategories.flatMap(cat =>
  cat.services.map(s => ({ ...s, category: cat.name, categoryId: cat.id, categoryColor: cat.color }))
)

export function searchServices(query) {
  const q = query.toLowerCase().trim()
  if (!q) return []
  
  // Intent-based matching
  const intentMap = {
    'lost': ['driving-licence', 'vehicle-registration'],
    'licence': ['driving-licence'],
    'license': ['driving-licence'],
    'dl': ['driving-licence'],
    'renew': ['driving-licence', 'vehicle-registration', 'passport'],
    'renewal': ['driving-licence', 'vehicle-registration', 'passport'],
    'passport': ['passport'],
    'college': ['scholarships', 'student-services', 'student-certificates'],
    'university': ['scholarships', 'student-services'],
    'engineering': ['scholarships', 'student-services'],
    'money': ['scholarships', 'epfo', 'payments', 'subsidies'],
    'financial help': ['scholarships', 'subsidies', 'employment-schemes'],
    'scholarship': ['scholarships', 'welfare-scholarships'],
    'tax': ['income-tax', 'gst'],
    'income tax': ['income-tax'],
    'pension': ['epfo', 'pensions'],
    'driving': ['driving-licence'],
    'car': ['vehicle-registration', 'traffic-fines'],
    'vehicle': ['vehicle-registration', 'traffic-fines'],
    'fine': ['traffic-fines'],
    'challan': ['traffic-fines'],
    'health': ['health-schemes', 'appointments', 'insurance'],
    'hospital': ['appointments'],
    'doctor': ['appointments'],
    'electricity': ['electricity'],
    'water': ['water'],
    'property': ['property'],
    'house': ['housing-schemes', 'property'],
    'aadhaar': ['aadhaar'],
    'pan card': ['pan'],
    'certificate': ['certificates', 'student-certificates', 'health-certificates'],
    'birth': ['certificates'],
    'death': ['certificates'],
    'income certificate': ['certificates'],
    'voter': ['voter'],
    'election': ['voter'],
    'job': ['employment-schemes', 'exams'],
    'employment': ['employment-schemes'],
    'benefit': ['welfare-scholarships', 'subsidies', 'state-benefits'],
    'check status': ['payments'],
    'application status': ['payments'],
  }

  // Check for exact intent matches
  for (const [keyword, serviceIds] of Object.entries(intentMap)) {
    if (q.includes(keyword)) {
      return serviceIds.map(id => flatServices.find(s => s.id === id)).filter(Boolean)
    }
  }

  // Fallback to keyword search
  return flatServices.filter(s =>
    s.name.toLowerCase().includes(q) ||
    s.description.toLowerCase().includes(q) ||
    s.category.toLowerCase().includes(q)
  )
}
